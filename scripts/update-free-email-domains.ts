// Writes shared/free-email-domains.ts from the npm package `free-email-domains` (MIT, microlinkhq).
// The list is copied into the repo, not added as a dependency.
//
//   bun scripts/update-free-email-domains.ts           # the latest version
//   bun scripts/update-free-email-domains.ts 1.16.16   # one version
//
// Then read the diff, run `bun run check`, and commit the new file.
const PKG = "free-email-domains";
const OUT = new URL("../shared/free-email-domains.ts", import.meta.url);

const meta = (await (
  await fetch(`https://registry.npmjs.org/${PKG}`)
).json()) as {
  "dist-tags": { latest: string };
  versions: Record<string, { license?: string }>;
};
const version = process.argv[2] ?? meta["dist-tags"].latest;
const license = meta.versions[version]?.license;
if (!license) throw new Error(`${PKG}@${version} is not on npm`);
const res = await fetch(
  `https://cdn.jsdelivr.net/npm/${PKG}@${version}/domains.json`,
);
if (!res.ok)
  throw new Error(`domains.json of ${PKG}@${version}: HTTP ${res.status}`);
const raw: unknown = await res.json();
if (!Array.isArray(raw)) throw new Error("domains.json is not a list");
const domains = [
  ...new Set(
    raw
      .filter((d): d is string => typeof d === "string")
      .map((d) => d.trim().toLowerCase())
      // Only plain host names: nothing in the list can break out of the string below.
      .filter((d) => /^[a-z0-9-]+(\.[a-z0-9-]+)+$/.test(d)),
  ),
].sort();
if (domains.length < 1000)
  throw new Error(`only ${domains.length} domains: refusing`);

await Bun.write(
  OUT,
  `// Generated by scripts/update-free-email-domains.ts. Do not change it by hand.
// Source: the npm package ${PKG}@${version} (${license} license, https://github.com/microlinkhq/free-email-domains),
// file domains.json: ${domains.length} domains of free and public email providers.
// Copyright © 2017 Microlink <hello@microlink.io> (microlink.io). MIT: the copyright notice stays with the copy.
// Only the Worker imports it (shared/org.ts, from src/): it is too large for the browser bundle.

export const FREE_EMAIL_DOMAINS_VERSION = ${JSON.stringify(`${PKG}@${version}`)};
/** The domains, one for each line. */
export const FREE_EMAIL_DOMAINS =
  ${JSON.stringify(domains.join("\n"))};
`,
);
console.log(
  `shared/free-email-domains.ts: ${PKG}@${version}, ${license}, ${domains.length} domains`,
);
