export type HomeLanguage = "pt" | "en";
export type HomeCopyKey = keyof typeof pt;
export const homeText = (
  lang: HomeLanguage,
  key: HomeCopyKey,
  vars: Record<string, string | number> = {},
) =>
  (lang === "en" ? en[key] : pt[key]).replace(/\{(\w+)\}/g, (_, key: string) =>
    String(vars[key] ?? ""),
  );
export function homeIssue(lang: HomeLanguage, error: string) {
  const keys = {
    network: "network",
    timeout: "unconfirmed",
    unconfirmed: "unconfirmed",
    empty: "emptyText",
    unavailable: "unavailable",
    "invalid-response": "invalidResponse",
  } as const;
  return Object.hasOwn(keys, error)
    ? homeText(lang, keys[error as keyof typeof keys])
    : error;
}
