export type ProfileLang = "pt" | "en";
export type ProfileCopyKey = keyof typeof pt;
export function profileText(
  lang: ProfileLang,
  key: ProfileCopyKey,
  vars: Record<string, string> = {},
) {
  return (lang === "en" ? en : pt)[key].replace(
    /\{(\w+)\}/g,
    (_, name: string) => vars[name] ?? "",
  );
}
